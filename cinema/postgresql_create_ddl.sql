CREATE TABLE tbl_scmv_m1(
    scmv_id CHAR(10) PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    summary VARCHAR(500) NOT NULL,
    playtime INT NOT NULL,
    agerating CHAR(1) NOT NULL,
    startdate DATE NOT NULL,
    enddate DATE,
    fee INT,
    status CHAR(1) NOT NULL
);

CREATE TABLE tbl_pers_m1(
    pers_id VARCHAR(34) PRIMARY KEY,
    name VARCHAR(30) NOT NULL
);

CREATE TABLE tbl_part_d1(
    part_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scmv_id CHAR(10) NOT NULL,
    pers_id VARCHAR(34) NOT NULL,
    FOREIGN KEY (scmv_id) REFERENCES tbl_scmv_m1(scmv_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (pers_id) REFERENCES tbl_pers_m1(pers_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE tbl_thtr_m1(
    thtr_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seat INT NOT NULL
);

CREATE TABLE tbl_seat_m1(
    seat_id VARCHAR(5) PRIMARY KEY,
    thtr_id INT NOT NULL,
    seatcode VARCHAR(3) NOT NULL,
    status CHAR(1) NOT NULL,
    FOREIGN KEY (thtr_id) REFERENCES tbl_thtr_m1(thtr_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE tbl_scrn_m1(
    scrn_id CHAR(12) PRIMARY KEY,
    scmv_id CHAR(10) NOT NULL,
    thtr_id INT NOT NULL,
    scrndate DATE NOT NULL,
    scrntime TIME NOT NULL,
    FOREIGN KEY (scmv_id) REFERENCES tbl_scmv_m1(scmv_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (thtr_id) REFERENCES tbl_thtr_m1(thtr_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE tbl_mbrt_l1(
    mbrt_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ratio INT NOT NULL
);

CREATE TABLE tbl_mebr_m1(
    mebr_id VARCHAR(16) PRIMARY KEY,
    passwd CHAR(64) NOT NULL,
    name VARCHAR(4) NOT NULL,
    birth DATE NOT NULL,
    sex CHAR(1) NOT NULL,
    phone CHAR(11) NOT NULL,
    email VARCHAR(50) NOT NULL,
    savings INT NOT NULL,
    mileage INT NOT NULL,
    mbrt_id INT NOT NULL DEFAULT 5,
    FOREIGN KEY (mbrt_id) REFERENCES tbl_mbrt_l1(mbrt_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE tbl_btpy_l1(
    btpy_id CHAR(1) PRIMARY KEY,
    method VARCHAR(10) NOT NULL
);

CREATE TABLE tbl_bytk_d1(
    bytk_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mebr_id VARCHAR(16) NOT NULL,
    scrn_id CHAR(12) NOT NULL,
    btpy_id CHAR(1) NOT NULL,
    buydate TIMESTAMP NOT NULL,
    savings INT NOT NULL,
    mileage INT NOT NULL,
    method CHAR(1) NOT NULL,
    seat_id VARCHAR(5), -- source data never populates this column; kept nullable
    FOREIGN KEY (seat_id) REFERENCES tbl_seat_m1(seat_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (mebr_id) REFERENCES tbl_mebr_m1(mebr_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (scrn_id) REFERENCES tbl_scrn_m1(scrn_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (btpy_id) REFERENCES tbl_btpy_l1(btpy_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE tbl_crpy_l1(
    crpy_id CHAR(1) PRIMARY KEY,
    method VARCHAR(10) NOT NULL
);

CREATE TABLE tbl_chrg_d1(
    chrg_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mebr_id VARCHAR(16) NOT NULL,
    amount INT NOT NULL,
    chargedate TIMESTAMP NOT NULL,
    crpy_id CHAR(1) NOT NULL,
    FOREIGN KEY (mebr_id) REFERENCES tbl_mebr_m1(mebr_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (crpy_id) REFERENCES tbl_crpy_l1(crpy_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE tbl_like_d1(
    scmv_id CHAR(10) NOT NULL,
    mebr_id VARCHAR(16) NOT NULL,
    PRIMARY KEY (scmv_id, mebr_id),
    FOREIGN KEY (scmv_id) REFERENCES tbl_scmv_m1(scmv_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (mebr_id) REFERENCES tbl_mebr_m1(mebr_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE tbl_mngr_m1(
    mngr_id VARCHAR(16) PRIMARY KEY,
    passwd CHAR(64) NOT NULL,
    name VARCHAR(4) NOT NULL,
    phone CHAR(11) NOT NULL,
    birth DATE NOT NULL,
    email VARCHAR(50) NOT NULL
);
