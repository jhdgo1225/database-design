CREATE TABLE tbl_scmv_m1(
    scmv_id CHAR(10) PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    summary VARCHAR(500) NOT NULL,
    playtime INT NOT NULL,
    agerating CHAR(1) NOT NULL,
    startdate DATE NOT NULL,
    enddate DATE,
    fee INT,
    status CHAR(1) NOT NULL
);

CREATE TABLE tbl_pers_m1(
    pers_id VARCHAR(34) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    eng_name VARCHAR(255) NOT NULL,
    country_code VARCHAR(3) NOT NULL CHECK (country_code IN ('KOR', 'USA', 'GBR', 'CHN', 'JPN')),
    birth DATE NULL
);

CREATE TABLE tbl_part_d1(
    scmv_id CHAR(10) NOT NULL,
	pers_id VARCHAR(34) NOT NULL,
    FOREIGN KEY (scmv_id) REFERENCES tbl_scmv_m1(scmv_id) ON UPDATE CASCADE ON DELETE RESTRICT,
	FOREIGN KEY (pers_id) REFERENCES tbl_pers_m1(pers_id) ON UPDATE CASCADE ON DELETE RESTRICT,
	PRIMARY KEY (scmv_id, pers_id)
);

CREATE TABLE tbl_thtr_m1(
    thtr_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seat INT NOT NULL,
    UNIQUE (thtr_id, seat) -- tbl_scrn_m1 이 (thtr_id, capacity) 로 참조하기 위한 대상 키
);

CREATE TABLE tbl_seat_m1(
    thtr_id INT NOT NULL,
    seatcode VARCHAR(3) NOT NULL,
    status CHAR(1) NOT NULL,
    FOREIGN KEY (thtr_id) REFERENCES tbl_thtr_m1(thtr_id) ON UPDATE CASCADE ON DELETE RESTRICT,
	PRIMARY KEY (thtr_id, seatcode)
);

CREATE TABLE tbl_scrn_m1(
    scrn_id CHAR(12) PRIMARY KEY,
    scmv_id CHAR(10) NOT NULL,
    thtr_id INT NOT NULL,
    capacity INT NOT NULL,     -- 상영 정원. tbl_thtr_m1.seat 를 반정규화한 값 (조인 제거용)
    scrndate DATE NOT NULL,
    scrntime TIME NOT NULL,
    UNIQUE (scrn_id, thtr_id), -- tbl_bytk_d1 이 (scrn_id, thtr_id) 로 참조하기 위한 대상 키
    FOREIGN KEY (scmv_id) REFERENCES tbl_scmv_m1(scmv_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    -- (thtr_id, capacity) 쌍이 tbl_thtr_m1 의 (thtr_id, seat) 와 항상 일치하도록 강제.
    -- thtr_id 의 존재 검사도 겸하므로 단일 컬럼 FK 는 두지 않는다.
    FOREIGN KEY (thtr_id, capacity) REFERENCES tbl_thtr_m1(thtr_id, seat) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE tbl_mebr_m1(
    mebr_id VARCHAR(16) PRIMARY KEY,
    passwd CHAR(64) NOT NULL,
    name VARCHAR(4) NOT NULL,
    birth DATE NOT NULL,
    sex CHAR(1) NOT NULL CHECK (sex IN ('M', 'F')),
    phone CHAR(11) NOT NULL,
    email VARCHAR(320) NOT NULL,
    savings INT NOT NULL CHECK (savings >= 0),
    mileage INT NOT NULL CHECK (mileage >= 0),
    rating INT NOT NULL DEFAULT 5 CHECK (rating >= 1 AND rating <= 5)
);

CREATE TABLE tbl_mngr_m1(
    mngr_id VARCHAR(16) PRIMARY KEY,
    passwd CHAR(64) NOT NULL,
    name VARCHAR(4) NOT NULL,
    phone CHAR(11) NOT NULL,
    birth DATE NOT NULL,
    email VARCHAR(50) NOT NULL
);

CREATE TABLE tbl_bytk_d1(
    bytk_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mebr_id VARCHAR(16) NOT NULL,
    scrn_id CHAR(12) NOT NULL,
    thtr_id INT NOT NULL,      -- (scrn_id, thtr_id) FK 로 상영의 상영관과 일치함을 보장
    seatcode VARCHAR(3),       -- 좌석 미지정(전화 예매 등)이면 NULL -> (thtr_id, seatcode) FK 검사 생략
    buy_method CHAR(1) NOT NULL CHECK (buy_method IN ('O', 'P')),   -- O 온라인 / P 전화
    reserved_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,     -- 예약을 시도한 시각
    pay_method CHAR(1) CHECK (pay_method IN ('A', 'B', 'C')),       -- A 적립금 / B 마일리지 / C 복합, NULL 이면 미결제
    buydate TIMESTAMPTZ,       -- 결제 완료 시각, NULL 이면 미결제
    savings INT NOT NULL,
    mileage INT NOT NULL,
    CHECK (   (pay_method IS NULL AND savings = 0 AND mileage = 0)
           OR (pay_method IS NOT NULL AND pay_method = 'A' AND savings > 0 AND mileage = 0)
           OR (pay_method IS NOT NULL AND pay_method = 'B' AND savings = 0 AND mileage > 0)
           OR (pay_method IS NOT NULL AND pay_method = 'C' AND savings > 0 AND mileage > 0)),
    CHECK (buy_method = 'P' OR pay_method IS NOT NULL),             -- 온라인 예매는 결제수단 필수
    CHECK ((buydate IS NULL) = (pay_method IS NULL)),               -- 결제 시각과 결제수단은 함께 존재
    FOREIGN KEY (mebr_id) REFERENCES tbl_mebr_m1(mebr_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (scrn_id, thtr_id) REFERENCES tbl_scrn_m1(scrn_id, thtr_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (thtr_id, seatcode) REFERENCES tbl_seat_m1(thtr_id, seatcode) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE tbl_chrg_d1(
    chrg_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mebr_id VARCHAR(16) NOT NULL,
    amount INT NOT NULL,
    charged_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    charge_method CHAR(1) NOT NULL CHECK (charge_method IN ('A', 'B', 'C', 'D', 'E')),
    FOREIGN KEY (mebr_id) REFERENCES tbl_mebr_m1(mebr_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE tbl_like_d1(
    scmv_id CHAR(10) NOT NULL,
    mebr_id VARCHAR(16) NOT NULL,
    PRIMARY KEY (scmv_id, mebr_id),
    FOREIGN KEY (scmv_id) REFERENCES tbl_scmv_m1(scmv_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (mebr_id) REFERENCES tbl_mebr_m1(mebr_id) ON UPDATE CASCADE ON DELETE RESTRICT
);


