-- =====================================================================
-- v2.1.0: 이용 불가 좌석을 상영 정원(capacity)에 반영하는 트리거
--
--   planned_capacity : 관리자가 입력하는 희망 정원
--   capacity         : 트리거가 계산하는 실제 이용 가능 정원
--     * 예정 상영 (시작 시각 > LOCALTIMESTAMP) : LEAST(planned_capacity, 현재 이용 가능 좌석수)
--     * 지난·상영 중 상영                       : planned_capacity 를 그대로 기록 (과거 기록 보존)
--
--   ① trg_calc_scrn_capacity : 상영 INSERT/UPDATE 시 planned_capacity 검증 + capacity 계산
--   ② trg_apply_seat_change  : 좌석 상태 변경 시 예정 상영의 capacity 재계산 (예매와 충돌하면 거부)
--   ③ trg_protect_thtr_seat  : 상영관 총 좌석수를 예정 상영의 희망 정원보다 작게 줄이는 변경 거부
--
--   동시성: tbl_thtr_m1 의 해당 행을 잠가 상영관 단위로 직렬화한다.
--           (상영 쪽 FOR SHARE, 좌석 쪽 FOR NO KEY UPDATE)
--           두 트리거의 잠금 순서는 "상영 행 -> 상영관 행" 으로 같다. (좌석 쪽이 예정 상영 행을 먼저 잠근다)
--   시간대: scrndate/scrntime 에 시간대가 없으므로 LOCALTIMESTAMP 로 비교한다.
--           DB 서버 시간대 = 극장 현지 시간이라고 가정한다.
-- =====================================================================

-- ① 상영 쪽: planned_capacity <= 총 좌석수 검사, capacity 계산
CREATE FUNCTION fn_calc_scrn_capacity() RETURNS trigger AS $$
DECLARE
    v_total INT;    -- 상영관 총 좌석수
    v_avail INT;    -- 현재 이용 가능 좌석수
BEGIN
    SELECT seat INTO v_total
    FROM tbl_thtr_m1
    WHERE thtr_id = NEW.thtr_id
    FOR SHARE;

    IF NOT FOUND THEN
        RAISE EXCEPTION '상영관 %가 존재하지 않습니다.', NEW.thtr_id
            USING ERRCODE = 'foreign_key_violation';
    END IF;

    IF NEW.planned_capacity > v_total THEN
        RAISE EXCEPTION '희망 정원(%)이 상영관 %의 총 좌석수(%)보다 클 수 없습니다.',
            NEW.planned_capacity, NEW.thtr_id, v_total
            USING ERRCODE = 'check_violation';
    END IF;

    IF (NEW.scrndate + NEW.scrntime) > LOCALTIMESTAMP THEN
        -- 예정 상영: 현재 이용 가능 좌석수로 제한
        SELECT COUNT(*) INTO v_avail
        FROM tbl_seat_m1
        WHERE thtr_id = NEW.thtr_id AND status = 'Y';

        NEW.capacity := LEAST(NEW.planned_capacity, v_avail);
    ELSIF TG_OP = 'INSERT'
       OR NEW.planned_capacity IS DISTINCT FROM OLD.planned_capacity
       OR NEW.thtr_id IS DISTINCT FROM OLD.thtr_id THEN
        -- 지난·상영 중 상영: 현재 좌석 상태와 무관하게 희망 정원을 그대로 기록
        NEW.capacity := NEW.planned_capacity;
    ELSE
        -- 지난·상영 중 상영의 다른 컬럼 수정: 기존 capacity 유지 (직접 쓴 값 무시)
        NEW.capacity := OLD.capacity;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_calc_scrn_capacity
    BEFORE INSERT OR UPDATE OF planned_capacity, thtr_id, scrndate, scrntime, capacity
    ON tbl_scrn_m1
    FOR EACH ROW
    EXECUTE FUNCTION fn_calc_scrn_capacity();

-- ② 좌석 쪽: 이용 가능 좌석수가 줄면 예매와의 충돌을 검사하고, 바뀌면 예정 상영의 capacity 를 재계산
CREATE FUNCTION fn_apply_seat_change() RETURNS trigger AS $$
DECLARE
    v_thtr_id  INT;
    v_seatcode VARCHAR(3);
    v_avail    INT;
    v_decrease BOOLEAN;   -- 이용 가능 좌석이 줄어드는 변경인가
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'Y' THEN RETURN NULL; END IF;       -- 이용 가능 수에 변화 없음
        v_thtr_id := NEW.thtr_id;  v_seatcode := NEW.seatcode;  v_decrease := FALSE;
    ELSIF TG_OP = 'DELETE' THEN
        IF OLD.status <> 'Y' THEN RETURN NULL; END IF;
        v_thtr_id := OLD.thtr_id;  v_seatcode := OLD.seatcode;  v_decrease := TRUE;
    ELSE
        IF OLD.status = NEW.status THEN RETURN NULL; END IF;
        v_thtr_id := NEW.thtr_id;  v_seatcode := NEW.seatcode;  v_decrease := (NEW.status = 'N');
    END IF;

    -- 잠금 순서는 "예정 상영 행(scrn_id 순) -> 상영관 행" 으로 둔다.
    -- 상영 UPDATE 트리거(fn_calc_scrn_capacity)가 "상영 행 -> 상영관 행(FOR SHARE)" 순서로 잠그므로,
    -- 순서를 맞추지 않으면 두 세션이 서로를 기다리는 데드락이 생긴다. (순서를 통일하기 전에는 부하 테스트에서 약 11% 발생)
    -- 상영관 행 잠금은 상영 INSERT 와 직렬화하기 위한 것이다.
    PERFORM 1 FROM tbl_scrn_m1 WHERE thtr_id = v_thtr_id AND (scrndate + scrntime) > LOCALTIMESTAMP ORDER BY scrn_id FOR UPDATE;
    PERFORM 1 FROM tbl_thtr_m1 WHERE thtr_id = v_thtr_id FOR NO KEY UPDATE;

    SELECT COUNT(*) INTO v_avail
    FROM tbl_seat_m1
    WHERE thtr_id = v_thtr_id AND status = 'Y';

    IF v_decrease THEN
        -- (i) 예정 상영에서 이 좌석을 이미 예매한 표가 있으면 거부
        IF EXISTS (
            SELECT 1
            FROM tbl_bytk_d1 AS b
            JOIN tbl_scrn_m1 AS s ON s.scrn_id = b.scrn_id
            WHERE b.thtr_id = v_thtr_id
              AND b.seatcode = v_seatcode
              AND (s.scrndate + s.scrntime) > LOCALTIMESTAMP
        ) THEN
            RAISE EXCEPTION '상영관 % 의 좌석 %는 예정 상영에 예매되어 있어 이용 불가로 바꿀 수 없습니다.',
                v_thtr_id, v_seatcode
                USING ERRCODE = 'check_violation';
        END IF;

        -- (ii) 예정 상영의 예매 수가 새 정원을 넘게 되면 거부 (전화 예약 등 결제 전 행도 센다)
        IF EXISTS (
            SELECT 1
            FROM tbl_scrn_m1 AS s
            WHERE s.thtr_id = v_thtr_id
              AND (s.scrndate + s.scrntime) > LOCALTIMESTAMP
              AND (SELECT COUNT(*) FROM tbl_bytk_d1 AS b WHERE b.scrn_id = s.scrn_id)
                  > LEAST(s.planned_capacity, v_avail)
        ) THEN
            RAISE EXCEPTION '상영관 %의 예정 상영 중 예매 수가 새 정원(이용 가능 좌석 %)을 넘는 상영이 있어 좌석 상태를 바꿀 수 없습니다.',
                v_thtr_id, v_avail
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    -- 예정 상영의 capacity 재계산 (지난·상영 중 상영은 건드리지 않음)
    UPDATE tbl_scrn_m1
    SET capacity = LEAST(planned_capacity, v_avail)
    WHERE thtr_id = v_thtr_id
      AND (scrndate + scrntime) > LOCALTIMESTAMP
      AND capacity IS DISTINCT FROM LEAST(planned_capacity, v_avail);

    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_apply_seat_change
    AFTER INSERT OR DELETE OR UPDATE OF status
    ON tbl_seat_m1
    FOR EACH ROW
    EXECUTE FUNCTION fn_apply_seat_change();

-- ③ 상영관 쪽: 총 좌석수를 예정 상영의 희망 정원보다 작게 줄이는 변경 거부
--    (복합 FK 의 ON UPDATE CASCADE 가 하던 자동 전파를 "차단"으로 대체)
CREATE FUNCTION fn_protect_thtr_seat() RETURNS trigger AS $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM tbl_scrn_m1
        WHERE thtr_id = NEW.thtr_id
          AND (scrndate + scrntime) > LOCALTIMESTAMP
          AND planned_capacity > NEW.seat
    ) THEN
        RAISE EXCEPTION '상영관 %의 총 좌석수를 %로 줄이면 희망 정원이 더 큰 예정 상영이 생깁니다.',
            NEW.thtr_id, NEW.seat
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_protect_thtr_seat
    BEFORE UPDATE OF seat
    ON tbl_thtr_m1
    FOR EACH ROW
    WHEN (NEW.seat < OLD.seat)
    EXECUTE FUNCTION fn_protect_thtr_seat();
