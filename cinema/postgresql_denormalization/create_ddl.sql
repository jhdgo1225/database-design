CREATE TABLE tbl_bytk_d1(
    bytk_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mebr_id VARCHAR(16) NOT NULL,
    scrn_id CHAR(12) NOT NULL,
    thtr_id INT NOT NULL,      -- (scrn_id, thtr_id) FK 로 상영의 상영관과 일치함을 보장
    seatcode VARCHAR(3),       -- 좌석 미지정(전화 예매 등)이면 NULL -> (thtr_id, seatcode) FK 검사 생략
    buy_method CHAR(1) NOT NULL CHECK (buy_method IN ('O', 'P')),   -- O 온라인 / P 전화
    reserved_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,     -- 예약을 시도한 시각
    pay_method CHAR(1) CHECK (pay_method IN ('A', 'B', 'C')),       -- A 적립금 / B 마일리지 / C 복합, NULL 이면 미결제
    buydate TIMESTAMPTZ,       -- 결제 완료 시각, NULL 이면 미결제
    savings INT NOT NULL,
    mileage INT NOT NULL,
    CHECK (   (pay_method IS NULL AND savings = 0 AND mileage = 0)
           OR (pay_method IS NOT NULL AND pay_method = 'A' AND savings > 0 AND mileage = 0)
           OR (pay_method IS NOT NULL AND pay_method = 'B' AND savings = 0 AND mileage > 0)
           OR (pay_method IS NOT NULL AND pay_method = 'C' AND savings > 0 AND mileage > 0)),
    CHECK (buy_method = 'P' OR pay_method IS NOT NULL),             -- 온라인 예매는 결제수단 필수
    CHECK ((buydate IS NULL) = (pay_method IS NULL)),               -- 결제 시각과 결제수단은 함께 존재
    FOREIGN KEY (mebr_id) REFERENCES tbl_mebr_m1(mebr_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (scrn_id, thtr_id) REFERENCES tbl_scrn_m1(scrn_id, thtr_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    FOREIGN KEY (thtr_id, seatcode) REFERENCES tbl_seat_m1(thtr_id, seatcode) ON UPDATE CASCADE ON DELETE RESTRICT
);

